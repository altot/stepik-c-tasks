/*
Печатаем числа

Напишите программу, которая выводит числа от 0 до 10 включительно.

Каждое число выводится на новой строке

Входные данные:

Отсутствуют

Выходные данные:

Числа от 0 до 10, выведенные по одному числу на строку.
*/
#include <stdio.h>
int main(void)
{
    int i = 0;
    int count = 11;
    for (i = 0; i < count; i++)
    {
        printf("%d\n", i);
    }

    return 0;
}