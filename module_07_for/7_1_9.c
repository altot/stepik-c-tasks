/*


На вход программе подаётся натуральное число M. Напишите программу, которая выводит на экран M символов *.

Входные данные:

Одно натуральное число M.

Выходные данные:

M символов *, записанных подряд без пробелов.
*/
#include <stdio.h>
int main(void)
{
    int n = 0;
    scanf("%d", &n);
    for (int i = 0; i < n; i++)
    {
        printf("*");
    }

    return 0;
}