/*
Написать программу выводящую на экран первые N натуральных чисел.

Входные данные:
Одно  целое число N, N>0

Выходные данные:
Первые N натуральных чисел, записанных через пробел.
*/
#include <stdio.h>
int main(void)
{
    int n = 0;
    scanf("%d", &n);
    for (int i = 1; i < n + 1; i++)
    {
        printf("%d ", i);
    }
    return 0;
}